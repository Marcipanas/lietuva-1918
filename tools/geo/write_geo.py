#!/usr/bin/env python3
"""Writes js/geo.js from tools/geo/geo.json, places.json and regions.json. Needs nothing beyond Python 3.
Run: python3 -I tools/geo/write_geo.py   (from the repository root; npm run geo does this)"""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
g = json.load(open(os.path.join(ROOT, 'tools/geo/geo.json')))
P = json.load(open(os.path.join(ROOT, 'tools/geo/places.json')))
R = json.load(open(os.path.join(ROOT, 'tools/geo/regions.json')))
J = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))
def flat(ring):
    """[[lon, lat], ...] as one list of 1/10000-degree steps from the previous point (geoRing decodes it)"""
    out, px, py = [], 0, 0
    for x, y in ring:
        ix, iy = round(x * 10000), round(y * 10000)
        out += [ix - px, iy - py]; px, py = ix, iy
    return out
rings = lambda rs: J([flat(r) for r in rs]) + '.map(geoRing)'
polys = lambda ws: J([{'o': flat(w['o']), 'h': [flat(h) for h in w['h']]} for w in ws]) + '.map(geoPoly)'
L = ["'use strict';",
     "/* Lietuva 1918 — geography in [lon, lat]. GENERATED by tools/geo (see tools/geo/README.md): do not edit by hand.",
     "   Borders: © OpenStreetMap contributors (ODbL). Coast, lakes and most rivers: Natural Earth (public domain), with rivers bent onto",
     "   the towns that stand on them. Place names and positions: EuroGeographics Euronym (EuroGeographics Open Data Licence).",
     "   Outlines are stored as steps of 1/10000 degree from the previous point. */",
     "function geoRing(a) { const out = []; let x = 0, y = 0; for (let i = 0; i < a.length; i += 2) { x += a[i]; y += a[i + 1]; out.push([x / 1e4, y / 1e4]); } return out; }",
     "function geoPoly(w) { return { o: geoRing(w.o), h: w.h.map(geoRing) }; }",
     "/* Lithuania's land: the mainland and its part of the Curonian Spit */",
     "const GEO_LT = " + rings(g['land_lt']) + ";",
     "/* the neighbours' land: Latvia, Belarus, Poland, and Russia's Kaliningrad region (East Prussia until 1945) */",
     "const GEO_C = { " + ", ".join(f"{k}: {rings(g['land_' + k])}" for k in ('lv', 'by', 'pl', 'ru')) + " };",
     "/* open sea and the Curonian Lagoon: outer ring o and islands h */",
     "const GEO_SEA = " + polys(g['sea']) + ";",
     "const GEO_LAG = " + polys(g['lagoon']) + ";",
     "/* borders between two countries a and b, over land and the lagoon */",
     "const GEO_BORD = " + J([{'a': b['a'], 'b': b['b'], 'p': flat(b['p'])} for b in g['borders']]) + ".map(b => ({ a: b.a, b: b.b, p: geoRing(b.p) }));",
     "/* the Klaipėda Region (Memel Territory, 1920–1939) */",
     "const GEO_KR = " + rings(g['kr']) + ";",
     "/* parts of today's Lithuania that changed hands later (tools/geo/build_regions.py): the Palanga strip (Latvian until 1921),",
     "   and the Vilnius region under Poland from 1920, in two parts: what came back in October 1939 and what in November 1940 */",
     "const GEO_KRW = " + polys(R['kr']) + ";  /* the Klaipėda Region widened past today's border, for the raster */",
     "const GEO_PAL = " + polys(R['pal']) + ";",
     "const GEO_V39 = " + polys(R['v39']) + ";",
     "const GEO_V40 = " + polys(R['v40']) + ";",
     "/* rivers from source to mouth: n name, w drawn width in km, thin: drawn only (too narrow for the terrain raster) */",
     "const GEO_RIV = " + J([{'n': r['n'], 'w': r['w'], 't': r['thin'], 'p': flat(r['p'])} for r in g['rivers']]) + ".map(r => ({ n: r.n, w: r.w, thin: r.t, p: geoRing(r.p) }));",
     "/* the bigger lakes as outlines (the smaller ones are LAKES in land.js) */",
     "const GEO_LAKES = " + rings([l['p'] for l in g['lakes']]) + ";",
     "/* towns and villages at their real places: [name, lon, lat, 1 = town or 0 = village, Euronym rank, residents today] */",
     "const PLACES = " + J([[p['n'], p['p'][0], p['p'][1], 1 if p['k'] == 'town' else 0, p['rs'], p['gp']] for p in P]) + ";"]
out = os.path.join(ROOT, 'js/geo.js')
open(out, 'w').write("\n".join(L) + "\n")
print('wrote js/geo.js,', os.path.getsize(out) // 1024, 'KB')
