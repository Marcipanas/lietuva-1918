#!/usr/bin/env node
/* Builds js/world1918.js, the start map: runs genWorld() once, headless, and stores the result in the save format.
   Generating takes a while, too long for a phone at every new game. Run it after changing the map data or the generator
   (npm run world); tools/check.js fails while the stored map is out of date. */
const fs = require('fs'), path = require('path'), vm = require('vm'), hash = require('./world-hash');
const root = path.join(__dirname, '..');
const SRC = ['js/common.js', 'js/data.js', 'js/geo.js', 'js/land.js', 'js/geom.js', 'js/terrain.js', 'js/world.js', 'js/sim.js', 'js/history.js'];
const ctx = { console, Math, Date, JSON, performance };
vm.createContext(ctx);
for (const f of SRC) vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
const t0 = Date.now();
const json = vm.runInContext(`S = { v: 6, day: 0, own: startOwners(), nid: 1, rid: 1, gid: 1, lid: 1, did: 1, towns: [], bld: [], routes: [], nodes: [], edges: [], lots: [] };
  genWorld(m => console.log('  ' + m)); JSON.stringify(Object.assign(encStartMap(), { ras: rasPack() }))`, ctx);
const out = path.join(root, 'js/world1918.js');
fs.writeFileSync(out, "'use strict';\n/* Lietuva 1918 — the start map. GENERATED by tools/build-world.js (npm run world): do not edit. */\nconst WORLD1918 = " +
  json.replace(/^\{/, `{"h":"${hash(root)}",`) + ';\n');
console.log(`wrote js/world1918.js: ${Math.round(fs.statSync(out).size / 1024)} KB in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
